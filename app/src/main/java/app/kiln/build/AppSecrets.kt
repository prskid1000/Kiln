package app.kiln.build

import java.io.File
import java.util.Base64

/**
 * Per-app secrets (API keys and the like). Names live in the project (.kiln/secrets.txt) so the
 * agent can refer to them; values live in Kiln's Keystore-backed store and only meet the code at
 * build time, as a generated `AppSecrets` object the app reads (`AppSecrets.WEATHER_KEY`).
 *
 * Anything shipped in an APK can be pulled out of it, so this keeps keys out of the source,
 * chats and GitHub — not out of the app. Only client-safe, restricted keys belong here.
 */
object AppSecrets {
    val NAME = Regex("^[A-Z][A-Z0-9_]{0,40}$")

    private fun list(p: Project) = File(p.kilnDir, "secrets.txt")

    fun names(p: Project): List<String> =
        runCatching { list(p).readLines() }.getOrDefault(emptyList()).map { it.trim() }.filter { NAME.matches(it) }.distinct()

    fun setNames(p: Project, names: List<String>) {
        p.kilnDir.mkdirs(); list(p).writeText(names.distinct().joinToString(System.lineSeparator()))
    }

    /** Where a value is kept in the secrets store. */
    fun storeId(p: Project, name: String) = "app_${p.name}_$name"

    /** The generated source; values are base64 so no escaping can break the Kotlin. */
    fun source(pkg: String, values: Map<String, String>): String = buildString {
        val nl = System.lineSeparator()
        append("package ").append(pkg).append(nl).append(nl)
        append("/** Generated by Kiln from this app's secrets — don't edit. Anything in an APK can be extracted. */").append(nl)
        append("object AppSecrets {").append(nl)
        for ((k, v) in values.toSortedMap()) {
            append("    val ").append(k).append(": String get() = String(android.util.Base64.decode(\"")
                .append(Base64.getEncoder().encodeToString(v.toByteArray())).append("\", android.util.Base64.NO_WRAP))").append(nl)
        }
        append("}").append(nl)
    }
}
